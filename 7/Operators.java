public class Operators {
	public static void main(String[] args) {
		int	n = 42;

		System.out.println(42 + 42);
		System.out.println(42 - 42);
		System.out.println(42 * 2);
		System.out.println(42 / 2);
		System.out.println(42 % 2);
		System.out.println("Vampeta " + "42");
		System.out.println("Vampeta " + 42);
		System.out.println(n++);
		System.out.println(n--);
		System.out.println(++n);
		System.out.println(--n);
		n += 1;
		System.out.println(n);
		n -= 1;
		System.out.println(n);
		n *= 2;
		System.out.println(n);
		n /= 2;
		System.out.println(n);
		n %= 2;
		System.out.println(n);
	}
}